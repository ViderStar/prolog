% Ограничиваем стек, чтобы переполнение наступало быстро.
:- set_prolog_flag(stack_limit, 20 000 000).

:- ensure_loaded('../family').

% 1. Singleton-переменная: Y встречается в клаузе один раз
%    (опечатка — должно было быть parent(X, _) или parent(X, Y), male(Y)).
has_child(X) :- parent(X, Y).

% 2. Разрывные (discontiguous) клаузы: sibling/2 прерывается
%    определением другого предиката.
sibling(X, Y) :- parent(P, X), parent(P, Y), X \== Y.
cousin(X, Y) :- parent(A, X), parent(B, Y), sibling(A, B).
sibling(liz, bob).

% 3. Левая рекурсия: рекурсивный вызов стоит первым,
%    поэтому поиск уходит в бесконечный спуск.
ancestor_bad(X, Y) :- ancestor_bad(Z, Y), parent(X, Z).
ancestor_bad(X, Y) :- parent(X, Y).
