% ============================================
% Логическая задача «Спортсмены»
% SWI-Prolog
% --------------------------------------------
% Практическая работа №2, задание 4 (вариант 3),
% «Стили и методы программирования. Часть 2».
%
% Условие. Тонни, Майкл и Джон — спортсмены.
% Один из них боксёр, другой футболист, третий
% пловец. Один любит снег, другой — дождь, третий —
% солнечную погоду.
%   1. Тот, кто любит солнечную погоду, — не боксёр.
%   2. Тонни не любит снег.
%   3. Майкл не любит солнечную погоду.
%   4. Футболист любит снег.
%   5. Тонни не пловец.
% Определить: у кого какая любимая погода и кто
% каким спортом занимается.
%
% Загрузка:  swipl sportsmen.pl
% Запуск:    ?- решить.
% ============================================

% Возможные значения признаков.
виды_спорта([боксёр, футболист, пловец]).
виды_погоды([снег, дождь, солнце]).

% решение(-Люди): Люди — список из трёх термов человек(Имя, Спорт, Погода),
% удовлетворяющий всем условиям задачи.
% Метод «образовать и проверить»: каждому из трёх признаков назначается
% одна из перестановок значений (так значения не повторяются),
% затем проверяются ограничения.
решение(Люди) :-
    Люди = [человек(тонни, С1, П1),
            человек(майкл, С2, П2),
            человек(джон,  С3, П3)],
    виды_спорта(Спорт),
    виды_погоды(Погода),
    permutation(Спорт,  [С1, С2, С3]),
    permutation(Погода, [П1, П2, П3]),
    ограничения(Люди).

% ограничения(+Люди): условия 1–5 из текста задачи.
ограничения(Люди) :-
    \+ member(человек(_, боксёр, солнце), Люди),     % 1
    \+ member(человек(тонни, _, снег), Люди),        % 2
    \+ member(человек(майкл, _, солнце), Люди),      % 3
    member(человек(_, футболист, снег), Люди),       % 4
    \+ member(человек(тонни, пловец, _), Люди).      % 5

% решить: найти все решения и напечатать их.
решить :-
    findall(Л, решение(Л), Решения),
    length(Решения, N),
    format("Найдено решений: ~d~n", [N]),
    forall(member(Л, Решения), вывести(Л)).

вывести(Люди) :-
    forall(member(человек(Имя, Спорт, Погода), Люди),
           format("~w: ~w, любит ~w~n", [Имя, Спорт, Погода])).
