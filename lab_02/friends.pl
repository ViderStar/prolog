% --- Факты ---
% день_рождения(Фамилия, Имя, День, Месяц, Год).
день_рождения(иванова, лена, 12, июнь, 1988).
день_рождения(сидоренко, вася, 25, март, 1987).
день_рождения(сидоренко, маша, 6, май, 1988).

% хобби(Фамилия, Имя, Хобби).
хобби(иванова, лена, книги).
хобби(сидоренко, маша, танцы).
хобби(сидоренко, вася, спорт).
хобби(сидоренко, вася, кино).
хобби(сидоренко, маша, кино).

% --- Правила ---
% друг(Ф, И): человек с фамилией Ф и именем И — друг;
% каждый друг указан в базе днём рождения.
друг(Ф, И) :- день_рождения(Ф, И, _, _, _).

% родился_в_году(Ф, И, Год): друг Ф И родился в году Год.
родился_в_году(Ф, И, Год) :- день_рождения(Ф, И, _, _, Год).

% родился_в_месяце(Ф, И, Месяц): друг Ф И родился в месяце Месяц.
родился_в_месяце(Ф, И, Месяц) :- день_рождения(Ф, И, _, Месяц, _).

% увлекается_обоими(Ф, И, Х1, Х2): у друга Ф И есть оба хобби — Х1 и Х2.
увлекается_обоими(Ф, И, Х1, Х2) :- хобби(Ф, И, Х1), хобби(Ф, И, Х2).

% --- Контрольные вопросы варианта ---
% ответы: печатает ответы на все вопросы подряд.
ответы :-
    вывести("Кто родился в 1988 году?",
            родился_в_году(Ф, И, 1988), Ф-И),
    вывести("Кто родился в мае?",
            родился_в_месяце(Ф, И, май), Ф-И),
    вывести("У кого хобби книги?",
            хобби(Ф, И, книги), Ф-И),
    вывести("Какое хобби у Маши?",
            хобби(_, маша, Х), Х),
    вывести("У кого хобби и кино, и спорт?",
            увлекается_обоими(Ф, И, кино, спорт), Ф-И),
    вывести("Фамилии и имена всех друзей:",
            друг(Ф, И), Ф-И).

% вывести(+Вопрос, :Цель, +Шаблон): напечатать вопрос и все решения Цели.
% Шаблон показывает, какие переменные Цели составляют ответ.
вывести(Вопрос, Цель, Шаблон) :-
    findall(Шаблон, Цель, Ответы),
    format("~s~n", [Вопрос]),
    (   Ответы == []
    ->  format("  никто~n")
    ;   forall(member(О, Ответы), format("  ~w~n", [О]))
    ).
